def style(status, config):
    level = status['level']
    role = config['appearance'].get(level, 'on_surface')
    accent = '@' + role
    if level in ('warning', 'critical', 'high'):
        background = f'mix(@surface_container, {accent}, 0.12)'
        islands = f'''window#waybar .modules-left, window#waybar #taskbar:not(.empty), window#waybar .modules-right {{
  background: alpha({background}, 0.94);
  border-color: alpha({accent}, 0.6);
}}'''
    else:
        islands = ''
    factor = status['policy']['animation_factor']
    mode_accent = '@' + {'performance': 'tertiary', 'balanced': 'secondary', 'complete': 'primary'}.get(status['mode'], 'secondary')
    duration = max(90, round(150 * factor)) if factor else 0
    scope = ', '.join(f'window#waybar .modules-{side} #{key}' for side in ('left','center','right') for key in ('clock','hardware','workspaces','custom-workspace-base','cpu','memory','temperature','disk','network','bluetooth','wireplumber','backlight','idle_inhibitor','custom-desktop-mode','custom-notification','custom-power','custom-updates','custom-hardware-toggle','tray','custom-music-open','custom-music-prev','custom-music-play','custom-music-next','taskbar button',*[f'custom-ws{i}' for i in range(1,11)]))
    motion = f'''{scope} {{ transition-duration: {duration}ms; }}''' if factor != 1 else ''
    if factor == 0:
        motion += '\n' + scope + ' { animation: none; transition: none; -gtk-icon-transform: none; }'
    elif factor < 1:
        motion += '\nwindow#waybar .modules-left, window#waybar .modules-center, window#waybar .modules-right { animation: none; }'
    return f'''/* Generated by desktop-power. Edit ~/.config/desktop-power/config.toml. */
{islands}
window#waybar #battery {{ color: {accent}; }}
window#waybar #battery.warning, window#waybar #battery.critical {{
  color: {accent}; background: alpha({accent}, 0.14); animation: none;
}}
window#waybar #custom-desktop-mode {{ color: {accent}; background: alpha({mode_accent}, 0.10); }}
window#waybar #custom-desktop-mode.warning, window#waybar #custom-desktop-mode.critical {{
  background: alpha({accent}, 0.14); animation: none;
}}
window#waybar #custom-desktop-mode:hover {{ background: alpha({accent}, 0.22); }}
{motion}
'''


def build_status(config, battery, previous, preference):
    source = preference.get('mode', 'auto')
    if source not in (*MODES, 'auto'):
        source = 'auto'
    prior = previous.get('mode') if previous.get('source') == 'auto' else None
    mode = choose_mode(source, battery, config['automation'], prior)
    profile = config['profiles'][mode]
    return {'mode': mode, 'source': source, 'label': profile['label'],
            'bar_label': profile['bar_label'], 'description': profile['description'],
            'battery': battery, 'level': battery_level(battery['percent'], config['automation']),
            'transition': False,
            'automation': config['automation'],
            'policy': {key: profile[key] for key in ('widgets', 'animation_factor', 'ambient_effects', 'animated_wallpaper')},
            'errors': dict(previous.get('errors', {})), 'notification_flags': dict(previous.get('notification_flags', {}))}


def fingerprint(config, status):
    paths = [HOME / '.config/wayfire.ini']
    stamps = [path.stat().st_mtime_ns if path.exists() else 0 for path in paths]
    data = [config['profiles'][status['mode']], stamps]
    return hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest()


def publish(status, config):
    write_json(STATUS, status)
    write_text(HOME / '.config/waybar/desktop-state.css', style(status, config))


def widget_visibility(status):
    if status['mode']=='complete' and status['policy']['widgets']:
        from .occlusion import suspended
        status['policy']['widgets']=not suspended()


def poll_interval(config,status,previous):
    auto=config['automation']
    stable=(status['battery'].get('plugged') is True and status['battery']==previous.get('battery')
            and not status['errors'] and status['mode']==previous.get('mode')
            and status['source']==previous.get('source'))
    return max(auto['poll_seconds'],auto.get('stable_ac_poll_seconds',15)) if stable else auto['poll_seconds']


def reconcile(previous, last_fingerprint=None, apply=True, retry=False):
    config = load_config()
    battery = read_battery()
    status = build_status(config, battery, previous, read_json(PREFERENCE))
    status['errors'].pop('config', None)
    original_flags = dict(status['notification_flags'])
    alerts, flags = notifications(battery, status['notification_flags'], config['automation'])
    status['notification_flags'] = flags
    if not alerts and not flags:
        status['errors'].pop('notification', None)
    if apply:widget_visibility(status)
    visibility_changed=status['policy']['widgets']!=previous.get('policy',{}).get('widgets')
    current_fingerprint = fingerprint(config, status)
    profile_changed = current_fingerprint != last_fingerprint or retry
    status['transition'] = bool(apply and (profile_changed or previous.get('source') != status['source']))
    publish(status, config)  # Widget/menu consumers see the policy before adapters run.
    if apply:
        profile = dict(config['profiles'][status['mode']], widgets=status['policy']['widgets'])
        if profile_changed:
            adapters = [('widgets-policy', effects.widget_policy), ('wayfire', lambda: effects.wayfire(profile, force=True)), ('cpu', lambda: effects.cpu(profile)),
                        ('focus', lambda: effects.focus_fx(profile))]
            if profile['widgets']:
                adapters.append(('widgets', lambda: effects.widgets(profile)))
            for name, function in adapters:
                if current_fingerprint == last_fingerprint and name not in status['errors']:
                    continue
                try:
                    function()
                    status['errors'].pop(name, None)
                except Exception as exc:
                    status['errors'][name] = str(exc)
        if visibility_changed and not profile_changed:
            try:
                effects.widget_policy()
                status['errors'].pop('widgets-policy',None)
            except Exception as exc:
                status['errors']['widgets-policy']=str(exc)
        if not profile['widgets'] or visibility_changed and not profile_changed or 'widgets' in status['errors'] or effects.widgets_need_install():
            # Editing is an explicit temporary exception. Reconcile its exit even
            # when the battery/profile itself has not changed.
            try:
                effects.widgets(profile)
                status['errors'].pop('widgets', None)
            except Exception as exc:
                status['errors']['widgets'] = str(exc)
        # Newly chosen video backgrounds must also obey an unchanged savings mode.
        try:
            effects.wallpaper(profile, config)
            status['errors'].pop('wallpaper', None)
        except Exception as exc:
            status['errors']['wallpaper'] = str(exc)
        if status['transition'] and profile['animation_factor'] > 0:
            try:
                effects.desktop_transition()
                status['errors'].pop('transition', None)
            except Exception as exc:
                status['errors']['transition'] = str(exc)
        for urgency, title, body in alerts:
            try:
                effects.run(['notify-send', '-a', 'desktop-power', '-i', 'battery-low-symbolic',
                             '-u', urgency, title, body])
                status['errors'].pop('notification', None)
            except Exception as exc:
                status['errors']['notification'] = str(exc)
                status['notification_flags'] = original_flags
        status['transition'] = False
        publish(status, config)
    return status, current_fingerprint, poll_interval(config,status,previous)


def daemon():
    STATE.mkdir(parents=True, exist_ok=True)
    with (STATE / 'daemon.lock').open('a+') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            return
        wake = threading.Event()
        signal.signal(signal.SIGUSR1, lambda *_: wake.set())
        lock.seek(0)
        lock.truncate()
        lock.write(json.dumps({'pid': os.getpid(), 'birth': effects.process_identity(os.getpid())[0]}))
        lock.flush()
        previous = read_json(STATUS)
        signature = None
        last_retry = 0
        while True:
            try:
                retry = bool(previous.get('errors')) and time.monotonic() - last_retry >= 30
                previous, signature, interval = reconcile(previous, signature, retry=retry)
                if retry:
                    last_retry = time.monotonic()
            except Exception as exc:
                print(f'desktop-power: {exc}', file=sys.stderr, flush=True)
                previous.setdefault('errors', {})['config'] = str(exc)
                write_json(STATUS, previous)
                interval = 5
            wake.wait(interval)
            wake.clear()


def ensure_daemon(wake=False):
    # The daemon enforces a flock, so concurrent bar instances cannot duplicate it.
    STATE.mkdir(parents=True, exist_ok=True)
    with (STATE / 'daemon.lock').open('a+') as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            if wake:
                try:
                    lock.seek(0)
                    owner = json.load(lock)
                    if effects.process_identity(owner['pid'])[0] == owner['birth']:
                        os.kill(owner['pid'], signal.SIGUSR1)
                except (OSError, ValueError, KeyError, TypeError):
                    pass
            return
    log = (STATE / 'daemon.log').open('a')
    subprocess.Popen([str(HOME / '.local/bin/desktop-power'), 'daemon'],
                     stdin=subprocess.DEVNULL, stdout=log, stderr=log, start_new_session=True)
    log.close()


def notify_mode(mode, applying=False, settled=True):
    names = {'auto': 'Auto', 'performance': 'Ahorro', 'balanced': 'Equilibrado', 'complete': 'Completo', 'working': 'Trabajo'}
    body = ('Ajustando el escritorio…' if applying else
            ('Según batería y cargador' if mode == 'auto' else 'Manual') if settled else
            'El escritorio sigue aplicando los cambios')
    title = ('Aplicando: ' if applying else 'Modo: ' if settled else 'Modo guardado: ') + names[mode]
    try:
        effects.run(['notify-send', '-a', 'desktop-power', '-i', 'preferences-system-power-symbolic',
                     '-r', '934271', '-t', '1800' if applying else '2200', title, body])
    except Exception as exc:
        # A notification failure must not undo a saved mode or break cycling.
        print('desktop-power: aviso de modo: ' + str(exc), file=sys.stderr)


def wait_for_mode(mode, timeout=45):
    """Wait until the daemon has finished applying the selected desktop policy."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        status = read_json(STATUS)
        selected = (status.get('source') == 'auto' if mode == 'auto' else
                    status.get('source') == mode and status.get('mode') == mode)
        if selected and not status.get('transition', False):
            return True
        time.sleep(0.1)
    return False


def select_mode(mode=None):
    """Cycle persisted intent, not delayed daemon status; serialize fast clicks."""
    order = ('auto', *MODES)
    PREFERENCE.parent.mkdir(parents=True, exist_ok=True)
    with (PREFERENCE.parent / 'preference.lock').open('a+') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if mode is None:
            current = read_json(PREFERENCE).get('mode', 'auto')
            if current not in order:
                current = 'auto'
            mode = order[(order.index(current) + 1) % len(order)]
        write_json(PREFERENCE, {'mode': mode})
    notify_mode(mode, applying=True)
    ensure_daemon(wake=True)
    settled = wait_for_mode(mode)
    # A faster later click owns the shared progress notification.
    if read_json(PREFERENCE).get('mode') == mode:
        notify_mode(mode, settled=settled)
    return mode


def bar_data(status, frame=0):
    if not status:
        return {'text': '󰂑 …', 'class': 'pending', 'tooltip': 'Starting…'}
    if not status.get('mode'):
        return {'text': '󰂃 !', 'class': 'error', 'tooltip': escape('Config.: ' + str(status.get('errors', {})))}
    battery = status['battery']
    capacity = battery.get('percent')
    percent = f"{capacity}%" if capacity is not None else 'Battery: no data'
    # Nerd Font battery family shared with the rest of the dock.
    icons = ('󰁺', '󰁻', '󰁼', '󰁽', '󰁾', '󰁿', '󰂀', '󰂁', '󰂂', '󰁹')
    icon = icons[min(9, max(0, (int(capacity) - 1) // 10))] if capacity is not None else '󰂑'
    if battery.get('plugged') and capacity is not None:
        icon = '󰂄' if capacity < 100 else '󰁹'
    elif status['level'] == 'critical':
        icon = '󰂃'
    source = 'Auto' if status['source'] == 'auto' else 'Manual'
    name = status.get('label') or {'performance': 'Power Saver', 'balanced': 'Balanced', 'complete': 'Performance', 'working': 'Work'}.get(status['mode'], status['mode'])
    plugged = {True: 'Plugged in', False: 'On battery', None: 'No charger'}[battery.get('plugged')]
    level = {'critical': ' · Critical', 'warning': ' · Low'}.get(status['level'], '')
    tooltip = f"{name} · {source}\n{percent}{level} · {plugged}\nClick: choose mode in Raccon Menu"
    if status.get('errors'):
        tooltip += '\nPending: ' + ', '.join(status['errors'])
    transition = bool(status.get('transition'))
    if transition:
        tooltip += '\nApplying mode…'
    return {'text': f"{icon} {percent if capacity is not None else '—'}",
            'alt': f'applying-{frame % 4}' if transition and status['policy']['animation_factor'] > 0 else ('auto' if status['source'] == 'auto' else status['mode']),
            'percentage': capacity or 0,
            'class': [status['mode'], status['level'], source.lower()] + (['applying'] if transition and status['policy']['animation_factor'] > 0 else []), 'tooltip': escape(tooltip)}


def main(argv):
    command = argv[0] if argv else 'status'
    if command == 'daemon':
        daemon()
    elif command == 'set' and len(argv) == 2 and argv[1] in (*MODES, 'auto'):
        select_mode(argv[1])
    elif command == 'cycle':
        select_mode()
    elif command == 'watch':
        ensure_daemon()
        last = None
        frame = 0
        while True:
            status = read_json(STATUS)
            transition = bool(status.get('transition'))
            output = json.dumps(bar_data(status, frame), ensure_ascii=False)
            if output != last:
                print(output, flush=True)
                last = output
            frame = (frame + 1) % 4 if transition else 0
            time.sleep(0.18 if transition else 0.5)
    elif command == 'status':
        print(json.dumps(read_json(STATUS), ensure_ascii=False, indent=2))
    elif command == 'modes':
        print(json.dumps(load_config()['profiles'], ensure_ascii=False))
    elif command == 'plan':
        config = load_config()
        print(json.dumps(build_status(config, read_battery(), read_json(STATUS), read_json(PREFERENCE)), ensure_ascii=False, indent=2))
    else:
        raise SystemExit('Usage: desktop-power daemon|watch|status|plan|modes|cycle|set auto|performance|balanced|complete|working')
